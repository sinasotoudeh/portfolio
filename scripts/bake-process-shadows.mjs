#!/usr/bin/env node
/**
 * Bakes the ProcessSection icons' phone drop-shadow into copies of the images (D-26).
 *
 * On phones the icons used a live CSS filter — drop-shadow(5px 12px 14px rgba(0,0,0,.25))
 * drop-shadow(1px 1px 0 rgba(255,255,255,.2)) — on an icon laid out 9vh tall (75.96px on an 844px
 * phone). This renders the same filter with Chromium's canvas (the same Skia filter code as CSS)
 * into public/images/Process/phone/<stage>/<name>.png, scaled to the source image's resolution,
 * with transparent padding for the shadow, and writes src/data/processPhoneIcons.ts with each
 * baked image's size and the padding the component uses to line the icon up exactly where the
 * filtered one was.
 *
 * Usage (repo root): node scripts/bake-process-shadows.mjs
 * Needs Playwright's Chromium from the machine-level tools dir ($PLAYWRIGHT_TOOLS_DIR or
 * ~/.local/share/portfolio-visual-tools) — never a dependency of this project.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';

const ROOT = process.cwd();
const TOOLS_DIR = process.env.PLAYWRIGHT_TOOLS_DIR ?? path.join(os.homedir(), '.local/share/portfolio-visual-tools');
const { chromium } = createRequire(path.join(TOOLS_DIR, 'package.json'))('playwright');

// The phone shadow as laid out: CSS px at an icon height of 9vh on an 844px-tall phone.
const REFERENCE_ICON_HEIGHT = 0.09 * 844;
const SHADOW = { x: 5, y: 12, blur: 14, color: 'rgba(0, 0, 0, 0.25)' };
const EDGE = { x: 1, y: 1, color: 'rgba(255, 255, 255, 0.2)' };

const dataFile = fs.readFileSync(path.join(ROOT, 'src/data/processData.ts'), 'utf8');
const sources = [...new Set([...dataFile.matchAll(/src: '(\/images\/Process\/[^']+\.png)'/g)].map(m => m[1]))];

const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto('about:blank');

const entries = [];
for (const src of sources) {
    const file = path.join(ROOT, 'public', src);
    const dataUrl = `data:image/png;base64,${fs.readFileSync(file).toString('base64')}`;
    const result = await page.evaluate(async ({ dataUrl, REFERENCE_ICON_HEIGHT, SHADOW, EDGE }) => {
        const img = new Image();
        img.src = dataUrl;
        await img.decode();
        const w = img.naturalWidth;
        const h = img.naturalHeight;
        const k = h / REFERENCE_ICON_HEIGHT; // source px per laid-out CSS px
        // A CSS drop-shadow blur radius r is a Gaussian with σ = r / 2; 3σ covers it.
        const reach = Math.ceil(1.5 * SHADOW.blur * k);
        const pad = {
            left: reach,
            top: reach,
            right: Math.ceil(reach + (SHADOW.x + EDGE.x) * k),
            bottom: Math.ceil(reach + (SHADOW.y + EDGE.y) * k),
        };
        const canvas = document.createElement('canvas');
        canvas.width = w + pad.left + pad.right;
        canvas.height = h + pad.top + pad.bottom;
        const ctx = canvas.getContext('2d');
        ctx.filter = `drop-shadow(${SHADOW.x * k}px ${SHADOW.y * k}px ${SHADOW.blur * k}px ${SHADOW.color}) drop-shadow(${EDGE.x * k}px ${EDGE.y * k}px 0 ${EDGE.color})`;
        ctx.drawImage(img, pad.left, pad.top);
        return { w, h, pad, width: canvas.width, height: canvas.height, png: canvas.toDataURL('image/png') };
    }, { dataUrl, REFERENCE_ICON_HEIGHT, SHADOW, EDGE });

    const outSrc = src.replace('/images/Process/', '/images/Process/phone/');
    const outFile = path.join(ROOT, 'public', outSrc);
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    fs.writeFileSync(outFile, Buffer.from(result.png.split(',')[1], 'base64'));
    entries.push({ src, phoneSrc: outSrc, ...result, png: undefined });
}
await browser.close();

const lines = entries.map(e =>
    `    '${e.src}': { src: '${e.phoneSrc}', width: ${e.width}, height: ${e.height}, left: ${e.pad.left}, top: ${e.pad.top}, right: ${e.pad.right}, bottom: ${e.pad.bottom} },`);
fs.writeFileSync(path.join(ROOT, 'src/data/processPhoneIcons.ts'), `// GENERATED by scripts/bake-process-shadows.mjs — do not edit by hand (D-26).
// Phone versions of the ProcessSection icons with their drop-shadow baked in: the baked image's
// size and the transparent padding (source px) around the original icon inside it.

export type PhoneIcon = { src: string; width: number; height: number; left: number; top: number; right: number; bottom: number };

export const PHONE_ICONS: Record<string, PhoneIcon> = {
${lines.join('\n')}
};
`);
console.log(`baked ${entries.length} icons → public/images/Process/phone/, src/data/processPhoneIcons.ts`);
